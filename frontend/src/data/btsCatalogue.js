// ── Derived helpers ──────────────────────────────────────────────────────────
export function getMemberByKey(key) {
  return BTS_MEMBERS.find((m) => m.key === key) || null
}

export function getAlbumById(id) {
  return BTS_CATALOGUE.find((a) => a.id === id) || null
}

export function formatReleaseDate(iso) {
  return new Date(`${iso}T00:00:00`).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  })
}

export function releaseTypeLabel(type) {
  const map = {
    studio_album: 'Studio Album',
    ep: 'EP',
    single_album: 'Single Album',
    compilation: 'Compilation',
    anthology: 'Anthology Album',
    live_album: 'Live Album',
    single: 'Single',
    ost: 'OST',
  }
  return map[type] || 'Release'
}

// Flattened track list with preview availability and album context.
export const ALL_BTS_SONGS = BTS_CATALOGUE.flatMap((album) =>
  album.tracks.map((track) => ({
    ...track,
    album: album.title,
    albumId: album.id,
    releaseDate: album.releaseDate,
    year: album.year,
    artist: album.artist,
    members: album.members || [],
    previewAvailable: Boolean(track.deezerId),
    imageUrl: album.imageUrl,
    source: album.source,
    sourceLastVerified: album.sourceLastVerified,
  }))
)

// Tracks verified to have a Deezer preview — safe to offer in the music picker.
export const allPreviewableSongs = ALL_BTS_SONGS.filter((s) => s.previewAvailable)

export function searchCatalogue(query = '') {
  const q = query.trim().toLowerCase()
  if (!q) return ALL_BTS_SONGS
  return ALL_BTS_SONGS.filter(
    (s) =>
      s.title.toLowerCase().includes(q) ||
      s.album.toLowerCase().includes(q) ||
      s.artist.toLowerCase().includes(q)
  )
}